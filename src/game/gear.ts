const pick8 = (m: Record<string, { url: string }>, t: string) => Array.from({ length: 8 }, (_, i) => {
  const key = Object.keys(m).find(k => k.endsWith(`${t}-${i}.png.asset.json`));
  const asset = key ? m[key] : undefined;
  if (!asset) throw new Error(`Missing ${t} direction ${i}`);
  return asset.url;
});
